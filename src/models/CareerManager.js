  resolveText(content) {
    if (!content) return '';
    if (typeof content === 'string') return content;
    return this.gender === 'female' ? (content.f || content.m || '') : (content.m || content.f || '');
  }

  getCurrentStage() {
    const raw = this.stages[this.currentStageIndex] || this.stages[0];
    return {
      ...raw,
      title: this.resolveText(raw.title),
      desc: this.resolveText(raw.desc)
    };
  }

  getCurrentEvent() {
    const stage = this.getCurrentStage();
    const events = this.stageEvents[stage.id] || [];
    return events[this.currentEventIndex] || null;
  }

  startCareer(name, gender, degree) {
    this.gender = gender || 'male';
    this.name = name || (this.gender === 'female' ? 'نور مصطفى' : 'أحمد مصطفى');
    this.degree = degree || 'تجارة إنجليزي';
    this.avatar = this.gender === 'female' ? './assets/characters/player_female.jpg' : './assets/characters/player.jpg';
    this.isStarted = true;
    this.currentStageIndex = 0;
    this.currentEventIndex = 0;
    this.activeDialogueState = null;
    this.saveCareer();
  }

  selectDialogueOption(optionIndex) {
    const event = this.getCurrentEvent();
    if (!event || !event.options[optionIndex]) return null;

    const opt = event.options[optionIndex];

    // Apply Stat Changes
    if (opt.statChanges) {
      if (opt.statChanges.skill) this.skill = Math.max(0, Math.min(100, this.skill + opt.statChanges.skill));
      if (opt.statChanges.integrity) this.integrity = Math.max(0, Math.min(100, this.integrity + opt.statChanges.integrity));
      if (opt.statChanges.networking) this.networking = Math.max(0, Math.min(100, this.networking + opt.statChanges.networking));
      if (opt.statChanges.wealth) this.wealth = Math.max(0, this.wealth + opt.statChanges.wealth);
      if (opt.statChanges.energy) this.energy = Math.max(0, Math.min(100, this.energy + opt.statChanges.energy));
    }

    // Add Perk if any
    if (opt.perkEarned && !this.acquiredPerks.some(p => p.id === opt.perkEarned.id)) {
      this.acquiredPerks.push(opt.perkEarned);
    }

    // Add monthly salary to wealth
    const stage = this.getCurrentStage();
    this.wealth += stage.baseSalary;

    const chosenText = this.resolveText(opt.text);
    const resolvedResult = this.resolveText(opt.resultText);

    // Save decision history
    this.decisionHistory.push({
      stage: stage.title,
      event: event.id,
      choiceText: chosenText,
      resultText: resolvedResult
    });

    // Save active dialogue interaction state
    this.activeDialogueState = {
      optionIndex,
      option: opt,
      isConcluded: true
    };

    this.saveCareer();

    return {
      event,
      option: opt,
      isCrossroads: !!opt.isFinalCrossroads,
      path: opt.path,
      resultText: resolvedResult,
      perkEarned: opt.perkEarned
    };
  }

  advanceToNextEvent() {
    const stage = this.getCurrentStage();
    const currentEvents = this.stageEvents[stage.id] || [];

    this.activeDialogueState = null;

    if (this.currentEventIndex + 1 < currentEvents.length) {
      this.currentEventIndex++;
    } else {
      // Advance to next stage!
      if (this.currentStageIndex + 1 < this.stages.length) {
        this.currentStageIndex++;
        this.currentEventIndex = 0;
      } else {
        this.isFinished = true;
      }
    }

    this.saveCareer();
  }

  chooseOption(optionIndex) {
    return this.selectDialogueOption(optionIndex);
  }

  exportToTycoon() {
    // Generates bootstrap parameters for GameState based on Career achievements
    const bonusFromSavings = Math.min(50000, Math.round(this.wealth * 0.5));
    const startingCash = 50000 + bonusFromSavings; // 50k to 100k
    const specialization = this.skill > this.networking ? (this.skill > this.integrity ? 'tech' : 'sme') : 'pr';
    const title = this.gender === 'female' ? 'رئيسة مجلس الإدارة' : 'رئيس مجلس الإدارة';

    return {
      managerName: this.name,
      managerGender: this.gender,
      startingCash,
      specialization,
      careerPerks: this.acquiredPerks,
      reputationBonus: Math.round((this.integrity + this.networking) / 10),
      summaryMsg: `تم استيراد خبرات ومسيرة ${title} [${this.name}]: رأس مال انطلاق مدعوم بـ ${startingCash.toLocaleString('ar-EG')} ج.م وسمعة سوقية +${Math.round((this.integrity + this.networking) / 10)}%!`
    };
  }

  saveCareer() {
    try {
      const data = {
        isStarted: this.isStarted,
        isFinished: this.isFinished,
        name: this.name,
        gender: this.gender,
        degree: this.degree,
        skill: this.skill,
        integrity: this.integrity,
        networking: this.networking,
        wealth: this.wealth,
        energy: this.energy,
        currentStageIndex: this.currentStageIndex,
        currentEventIndex: this.currentEventIndex,
        acquiredPerks: this.acquiredPerks,
        decisionHistory: this.decisionHistory,
        activeDialogueState: this.activeDialogueState
      };
      localStorage.setItem('egyptian_bank_career', JSON.stringify(data));
      if (typeof window !== 'undefined' && window.cloudSaveService) {
        window.cloudSaveService.requestAutoSave();
      }
    } catch (e) {
      console.warn('LocalStorage saveCareer failed', e);
    }
  }

  loadCareer() {
    try {
      const saved = localStorage.getItem('egyptian_bank_career');
      if (saved) {
        const data = JSON.parse(saved);
        this.isStarted = data.isStarted || false;
        this.isFinished = data.isFinished || false;
        this.name = data.name || this.name;
        this.gender = data.gender || this.gender;
        this.degree = data.degree || this.degree;
        this.avatar = (this.gender === 'female') ? './assets/characters/player_female.jpg' : './assets/characters/player.jpg';
        this.skill = data.skill ?? this.skill;
        this.integrity = data.integrity ?? this.integrity;
        this.networking = data.networking ?? this.networking;
        this.wealth = data.wealth ?? this.wealth;
        this.energy = data.energy ?? this.energy;
        this.currentStageIndex = data.currentStageIndex || 0;
        this.currentEventIndex = data.currentEventIndex || 0;
        this.acquiredPerks = data.acquiredPerks || [];
        this.decisionHistory = data.decisionHistory || [];
        this.activeDialogueState = data.activeDialogueState || null;
      }
    } catch (e) {
      console.warn('LocalStorage loadCareer failed', e);
    }
  }

